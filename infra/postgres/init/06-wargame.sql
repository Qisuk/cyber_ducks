-- range_control database: wargame / Ops Console state (ADR-0008, hosted in range-control).
-- Scenarios (briefing, injects) are files in wargame/scenarios; these tables hold what happens
-- during an exercise. Lives beside the defence flags, so store roles can't reach it either.
-- Built for one player now, but sessions, participants and roles are modelled from day one.

\connect range_control

SET ROLE range_control_owner;

CREATE TABLE exercises (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id  text        NOT NULL,                 -- file name in wargame/scenarios (without .yaml)
    title        text        NOT NULL,
    status       text        NOT NULL DEFAULT 'planned'
                 CHECK (status IN ('planned', 'running', 'ended')),
    -- Clock speed: 1 = real time, 60 = a scenario minute every real second (for demo / runthrough).
    -- With autoplay on, injects auto-release as their scaled at_minute arrives (ExerciseClock).
    speed        numeric(6,2) NOT NULL DEFAULT 1 CHECK (speed > 0),
    autoplay     boolean     NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now(),
    started_at   timestamptz,
    ended_at     timestamptz
);

-- Roles from ADR-0008. Only the facilitator sees ground truth.
CREATE TABLE participants (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id  integer NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    name         text    NOT NULL,
    role         text    NOT NULL CHECK (role IN
                 ('facilitator', 'incident_commander', 'tech_lead', 'comms', 'legal_dpo', 'exec')),
    UNIQUE (exercise_id, name)
);

-- Which scenario injects have been released, and when (the injects themselves are in the file).
CREATE TABLE inject_releases (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id  integer     NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    inject_id    text        NOT NULL,
    released_at  timestamptz NOT NULL DEFAULT now(),
    released_by  text        NOT NULL,
    UNIQUE (exercise_id, inject_id)
);

-- The decision log. Phases follow NIST SP 800-61r2's incident-response lifecycle.
CREATE TABLE decisions (
    id              integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id     integer     NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    participant_id  integer     REFERENCES participants (id) ON DELETE SET NULL,
    made_at         timestamptz NOT NULL DEFAULT now(),
    phase           text        NOT NULL CHECK (phase IN
                    ('preparation', 'detection_analysis', 'containment_eradication_recovery', 'post_incident')),
    decision        text        NOT NULL,
    rationale       text        NOT NULL DEFAULT ''
);

-- Map state history, one row per change (append-only); the current state is the latest row per
-- (node, layer). Two layers: what the players have detected, and what is actually true. The gap
-- between them is a core learning outcome.
CREATE TABLE node_state_changes (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id  integer     NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    node         text        NOT NULL,                 -- a service name from infra/topology.yaml
    layer        text        NOT NULL CHECK (layer IN ('detected', 'ground_truth')),
    state        text        NOT NULL CHECK (state IN
                 ('normal', 'suspected', 'compromised', 'contained', 'recovered')),
    note         text        NOT NULL DEFAULT '',
    changed_at   timestamptz NOT NULL DEFAULT now(),
    changed_by   text        NOT NULL
);

CREATE INDEX node_state_changes_current ON node_state_changes (exercise_id, node, layer, id DESC);

-- Facilitator-authored timeline messages: ad-hoc injects and notes added live during an exercise
-- (the scenario's own injects stay in the file). These show in players' feeds, filtered by audience,
-- and in the after-action timeline. Editable and deletable while the exercise runs.
CREATE TABLE timeline_messages (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id  integer     NOT NULL REFERENCES exercises (id) ON DELETE CASCADE,
    phase        text        NOT NULL DEFAULT 'detection_analysis' CHECK (phase IN
                 ('preparation', 'detection_analysis', 'containment_eradication_recovery', 'post_incident')),
    audience     text[]      NOT NULL DEFAULT '{all}',
    sender       text        NOT NULL DEFAULT 'Facilitator',
    title        text        NOT NULL,
    body         text        NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by   text        NOT NULL
);

CREATE INDEX timeline_messages_exercise ON timeline_messages (exercise_id, created_at);

RESET ROLE;
