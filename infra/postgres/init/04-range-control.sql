-- range_control database: defence flags and presets (ADR-0011, docs/data-model.md).
-- Separate database; store roles have no CONNECT privilege on it (01-roles.sh).

\connect range_control

SET ROLE range_control_owner;

CREATE TABLE defence_flags (
    vuln_id           text        PRIMARY KEY,                    -- e.g. VULN-IDOR-01
    title             text        NOT NULL,
    kind              text        NOT NULL CHECK (kind IN ('code', 'infra', 'data')),
    mode              text        NOT NULL DEFAULT 'vulnerable'
                      CHECK (mode IN ('vulnerable', 'secure')),
    requires_restart  boolean     NOT NULL DEFAULT false,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        text        NOT NULL DEFAULT 'seed'
);

CREATE TABLE presets (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    description  text NOT NULL DEFAULT ''
);

CREATE TABLE preset_flags (
    preset_id  integer NOT NULL REFERENCES presets (id),
    vuln_id    text    NOT NULL REFERENCES defence_flags (vuln_id),
    mode       text    NOT NULL CHECK (mode IN ('vulnerable', 'secure')),
    PRIMARY KEY (preset_id, vuln_id)
);

-- History of every change. Also sent to telemetry as a Grafana annotation.
CREATE TABLE flag_changes (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at  timestamptz NOT NULL DEFAULT now(),
    vuln_id     text        NOT NULL REFERENCES defence_flags (vuln_id),
    old_mode    text        NOT NULL,
    new_mode    text        NOT NULL,
    changed_by  text        NOT NULL
);

-- Record every mode change and notify listening services (they refresh their flag cache).
CREATE FUNCTION on_flag_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.mode IS DISTINCT FROM OLD.mode THEN
        INSERT INTO flag_changes (vuln_id, old_mode, new_mode, changed_by)
        VALUES (NEW.vuln_id, OLD.mode, NEW.mode, NEW.updated_by);
        PERFORM pg_notify('defence_flags', NEW.vuln_id);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER defence_flags_changed
    AFTER UPDATE ON defence_flags
    FOR EACH ROW EXECUTE FUNCTION on_flag_change();

RESET ROLE;

-- Range services may only read the flags.
GRANT USAGE ON SCHEMA public TO flags_reader;
GRANT SELECT ON defence_flags TO flags_reader;
