-- duckstore schema (docs/data-model.md). Runs once on first start.
-- Objects are created as store_owner so that role owns them.
-- ✎ = free-text field: deliberate carrier for stored XSS / indirect prompt injection (T7).
-- Toggleable constraints ("guards") are NOT defined here: see 03-guards.sql.

SET ROLE store_owner;

-- Users: customers and staff in one table (decision 1).
CREATE TABLE users (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 text        NOT NULL UNIQUE,
    display_name          text        NOT NULL,                       -- ✎
    role                  text        NOT NULL DEFAULT 'customer'
                          CHECK (role IN ('customer', 'employee', 'admin', 'auditor')),
    password_hash_legacy  text,       -- insecure-mode credential storage (ADR-0011 dual column)
    password_hash         text,       -- secure-mode credential storage, computed by the app
    failed_login_count    integer     NOT NULL DEFAULT 0,  -- lockout state (VULN-AUTH-01), enforced only in secure mode
    locked_until          timestamptz,                     -- NULL = not locked
    created_at            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN users.role IS 'Asset A17. Target of mass assignment (TH7).';
COMMENT ON COLUMN users.password_hash_legacy IS 'Insecure mode (A4). Cleared by the range-control purge action.';

-- Social logins linked to a user (used from Phase 5).
CREATE TABLE user_identities (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer     NOT NULL REFERENCES users (id),
    provider        text        NOT NULL CHECK (provider IN ('google', 'meta')),
    subject         text        NOT NULL,
    email           text,
    email_verified  boolean     NOT NULL DEFAULT false,
    linked_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, subject)
);
CREATE INDEX ON user_identities (user_id);

-- The ducks.
CREATE TABLE products (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text           NOT NULL UNIQUE,
    name         text           NOT NULL,
    description  text           NOT NULL DEFAULT '',
    price        numeric(10,2)  NOT NULL,
    stock        integer        NOT NULL DEFAULT 0,
    image_url    text,
    visible      boolean        NOT NULL DEFAULT true  -- false = not shown in the catalogue list (CTF hidden-duck)
);

CREATE TABLE product_reviews (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  integer     NOT NULL REFERENCES products (id),
    user_id     integer     NOT NULL REFERENCES users (id),
    rating      smallint    NOT NULL CHECK (rating BETWEEN 1 AND 5),
    body        text        NOT NULL DEFAULT '',                  -- ✎
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON product_reviews (product_id);

-- Orders: sequential numbers from 1001, so object IDs are guessable (TH4).
CREATE TABLE orders (
    id                integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    user_id           integer     NOT NULL REFERENCES users (id),
    status            text        NOT NULL DEFAULT 'placed'
                      CHECK (status IN ('placed', 'paid', 'shipped', 'delivered', 'cancelled')),
    notes             text        NOT NULL DEFAULT '',            -- ✎
    shipping_address  text        NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    shipped_at        timestamptz
);
CREATE INDEX ON orders (user_id);

-- Order lines. Quantity/price limits are guards (03-guards.sql), off by default.
CREATE TABLE order_items (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer        NOT NULL REFERENCES orders (id),
    product_id  integer        NOT NULL REFERENCES products (id),
    quantity    integer        NOT NULL,
    unit_price  numeric(10,2)  NOT NULL                           -- price captured at order time
);
CREATE INDEX ON order_items (order_id);

CREATE TABLE invoices (
    id          integer GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
    order_id    integer        NOT NULL UNIQUE REFERENCES orders (id),
    amount_due  numeric(10,2)  NOT NULL,
    status      text           NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid', 'void')),
    due_date    date           NOT NULL,
    paid_at     timestamptz
);

CREATE TABLE payments (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    integer        NOT NULL REFERENCES invoices (id),
    amount        numeric(10,2)  NOT NULL,
    provider_ref  text,
    status        text           NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'succeeded', 'failed')),
    created_at    timestamptz    NOT NULL DEFAULT now()
);
CREATE INDEX ON payments (invoice_id);

-- "Remember my card" (ADR-0007, ADR-0011 dual columns). Test card numbers only, ever.
CREATE TABLE saved_cards (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer     NOT NULL REFERENCES users (id),
    cardholder_name  text        NOT NULL,
    card_number      text,       -- insecure mode: full card number (A2). Cleared by purge.
    card_cvv         text,       -- insecure mode: never allowed under PCI DSS. Cleared by purge.
    payment_token    text,       -- secure mode: provider token
    last4            text        NOT NULL,
    expiry_month     smallint    NOT NULL CHECK (expiry_month BETWEEN 1 AND 12),
    expiry_year      smallint    NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON saved_cards (user_id);

-- Security events. Created but deliberately left unused in the alpha (TH3, TH12).
CREATE TABLE audit_log (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  timestamptz NOT NULL DEFAULT now(),
    user_id      integer     REFERENCES users (id),
    action       text        NOT NULL,
    object_type  text,
    object_id    text,
    source_ip    inet,
    trace_id     text,
    details      jsonb       NOT NULL DEFAULT '{}'
);

-- CTF flag submissions (the "post a flag" path). Attackers submit a captured flag plus a note on
-- how they got it, for flags grabbed without tripping a log. Append-only for the app; the
-- facilitator reads them on the Range Control scoreboard. The `secrets` table is a SQLi target
-- (its row carries the sqli-secret flag, set per deployment by FlagSeeder).
CREATE TABLE flag_submissions (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flag_text    text        NOT NULL,
    note         text,
    how          text,
    team         text,                            -- attacker team name, for the public leaderboard
    source_ip    text,
    recognised   boolean     NOT NULL DEFAULT false,
    matched_slug text,
    submitted_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE secrets (
    id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text NOT NULL,
    value text NOT NULL
);

RESET ROLE;

-- Least-privilege grants for store_app (secure DB-role mode). No DELETE anywhere;
-- audit_log is append-only for the app.
GRANT SELECT, INSERT, UPDATE ON users, user_identities, orders, order_items,
      invoices, payments, saved_cards, product_reviews TO store_app;
GRANT SELECT ON products TO store_app;
GRANT UPDATE (stock) ON products TO store_app;
GRANT INSERT ON audit_log TO store_app;
-- Flag submissions: the app may append and read back; secrets are readable (the SQLi target).
GRANT SELECT, INSERT ON flag_submissions TO store_app;
GRANT SELECT ON secrets TO store_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO store_app;

-- The facilitator role (range-control's FlagSeeder) places the per-deployment CTF flags into the
-- store data (a ghost user's name, an order's notes, the secrets row, a hidden duck, a card ref),
-- and reads submissions for the scoreboard.
GRANT SELECT, INSERT, UPDATE ON users, orders, order_items, products, saved_cards, secrets TO range_control_owner;
GRANT SELECT ON flag_submissions TO range_control_owner;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO range_control_owner;
