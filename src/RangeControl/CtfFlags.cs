using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text;
using Npgsql;

namespace RangeControl;

public sealed record CtfFlag(string Slug, Guid? Guid, string? VulnId, string Title, string WhereHint, int Points, bool Placed);
public sealed record FlagSubmission(long Id, string FlagText, string? Note, string? How, string? SourceIp, bool Recognised, string? MatchedSlug, DateTimeOffset At);

/// <summary>
/// Reads the CTF flag manifest (range_control.ctf_flags) and the attacker submissions
/// (duckstore.flag_submissions) for the Range Control scoreboard, and matches submitted text to the
/// per-deployment flag guids. Flag values are never in Git — they are generated by <see cref="FlagSeeder"/>.
/// </summary>
public sealed class CtfFlagService(NpgsqlDataSource controlDb, NpgsqlDataSource storeDb)
{
    public async Task<IReadOnlyList<CtfFlag>> GetManifestAsync(CancellationToken ct = default)
    {
        var list = new List<CtfFlag>();
        await using var cmd = controlDb.CreateCommand(
            "SELECT slug, guid, vuln_id, title, where_hint, points, placed FROM ctf_flags ORDER BY points, slug");
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
            list.Add(new CtfFlag(r.GetString(0), r.IsDBNull(1) ? null : r.GetGuid(1),
                r.IsDBNull(2) ? null : r.GetString(2), r.GetString(3), r.GetString(4), r.GetInt32(5), r.GetBoolean(6)));
        return list;
    }

    /// <summary>Clear all attacker submissions — a fresh scoreboard for the next round.</summary>
    public async Task ResetSubmissionsAsync(CancellationToken ct = default)
    {
        await using var cmd = storeDb.CreateCommand("DELETE FROM flag_submissions");
        await cmd.ExecuteNonQueryAsync(ct);
    }

    public async Task<IReadOnlyList<FlagSubmission>> GetSubmissionsAsync(CancellationToken ct = default)
    {
        var list = new List<FlagSubmission>();
        await using var cmd = storeDb.CreateCommand(
            "SELECT id, flag_text, note, how, source_ip, recognised, matched_slug, submitted_at FROM flag_submissions ORDER BY submitted_at DESC LIMIT 500");
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
            list.Add(new FlagSubmission(r.GetInt64(0), r.GetString(1), r.IsDBNull(2) ? null : r.GetString(2),
                r.IsDBNull(3) ? null : r.GetString(3), r.IsDBNull(4) ? null : r.GetString(4), r.GetBoolean(5),
                r.IsDBNull(6) ? null : r.GetString(6), r.GetFieldValue<DateTimeOffset>(7)));
        return list;
    }
}

/// <summary>
/// Generates the per-deployment flag guids (so real flag values never live in Git) and places the
/// data-embedded flags into the store data. Runs once at startup; idempotent.
/// </summary>
public sealed class FlagSeeder(
    NpgsqlDataSource controlDb, NpgsqlDataSource storeDb, IHttpClientFactory httpFactory, ILogger<FlagSeeder> log) : IHostedService
{
    private static string Flag(Guid g) => $"flag{{{g}}}";

    public Task StartAsync(CancellationToken ct) => SeedAsync(regenerate: false, ct);

    /// <summary>
    /// Generate+place flags. regenerate=false (startup) only fills missing guids; regenerate=true
    /// (facilitator "new round") mints fresh guids for every flag and re-places them.
    /// </summary>
    public async Task SeedAsync(bool regenerate, CancellationToken ct)
    {
        try
        {
            // 1. GUIDs. On regenerate, mint fresh ones for all flags and clear placed/grafana state.
            var genSql = regenerate
                ? "UPDATE ctf_flags SET guid = gen_random_uuid(), placed = false"
                : "UPDATE ctf_flags SET guid = gen_random_uuid() WHERE guid IS NULL";
            await using (var gen = controlDb.CreateCommand(genSql))
                await gen.ExecuteNonQueryAsync(ct);

            // 2. Read the guids we place as data.
            var g = new Dictionary<string, Guid>();
            await using (var read = controlDb.CreateCommand("SELECT slug, guid FROM ctf_flags WHERE guid IS NOT NULL"))
            await using (var r = await read.ExecuteReaderAsync(ct))
                while (await r.ReadAsync(ct)) g[r.GetString(0)] = r.GetGuid(1);

            // 3. Place the data-embedded flags in duckstore (idempotent upserts).
            await PlaceNoLoginUser(g, ct);
            await PlaceIdorOrder(g, ct);
            await PlaceSqliSecret(g, ct);
            await PlacePciCard(g, ct);
            await PlaceVictimOrder(g, "reset-takeover", 1097, 3, ct);       // reset carol's password, then read her order
            await PlaceVictimOrder(g, "cred-stuffing", 1095, 1, ct);        // stuff alice's weak password, then read her order
            await PlaceVictimOrder(g, "agent-crosscustomer", 1094, 4, ct);  // get the AI agent to return Dave's order
            await PlaceHiddenDuck(g, ct);
            await PlaceBackupSecret(g, ct);     // backup.sh reads this and writes it into the backups volume
            await PlaceGrafanaAnnotation(g, ct); // one Grafana annotation carrying the flag

            // 4. Code-served flags are live as soon as their service is deployed — mark them placed.
            // (honeypot-bait / egress-exfil are served by the honeypot; webhook-forge by store-api.)
            foreach (var slug in new[] { "hidden-endpoint", "unlinked-page", "staff-banner", "authz-api",
                         "admin-view", "secret-tool", "webhook-forge", "honeypot-bait", "egress-exfil" })
                await MarkPlaced(slug, ct);

            log.LogInformation("CTF flags generated; data + code-served flags placed.");
        }
        catch (Exception ex)
        {
            log.LogWarning(ex, "CTF flag seeding failed.");
        }
    }

    public Task StopAsync(CancellationToken ct) => Task.CompletedTask;

    // A user that exists but can never sign in (NULL password). The flag is its display_name, so it
    // surfaces on any user enumeration or a dump of the users table.
    private async Task PlaceNoLoginUser(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("nologin-user", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO users (id, email, display_name, role, created_at)
            VALUES (98, 'service.account@duckstore.test', @name, 'customer', '2026-07-15 00:00+00')
            ON CONFLICT (id) DO UPDATE SET display_name = EXCLUDED.display_name
            """);
        cmd.Parameters.AddWithValue("name", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("nologin-user", ct);
    }

    // An order owned by Bob (user 2). Reading it as anyone else is IDOR; the flag is in the notes.
    private async Task PlaceIdorOrder(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("idor-order", out var guid)) return;
        await using (var o = storeDb.CreateCommand("""
            INSERT INTO orders (id, user_id, status, notes, shipping_address, created_at, updated_at, shipped_at)
            VALUES (1098, 2, 'delivered', @notes, '7 Mallard Street, Duckton, DT2 2BB', '2026-09-20 10:00+00', '2026-09-25 12:00+00', '2026-09-22 09:00+00')
            ON CONFLICT (id) DO UPDATE SET notes = EXCLUDED.notes
            """))
        {
            o.Parameters.AddWithValue("notes", $"Leave with neighbour. {Flag(guid)}");
            await o.ExecuteNonQueryAsync(ct);
        }
        await using (var i = storeDb.CreateCommand(
            "INSERT INTO order_items (id, order_id, product_id, quantity, unit_price) VALUES (9098, 1098, 1, 1, 4.99) ON CONFLICT (id) DO NOTHING"))
            await i.ExecuteNonQueryAsync(ct);
        await MarkPlaced("idor-order", ct);
    }

    // A row in the secrets table, reachable only by SQL injection in the product search (UNION dump).
    private async Task PlaceSqliSecret(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("sqli-secret", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO secrets (id, name, value) VALUES (1, 'ctf-flag', @val)
            ON CONFLICT (id) DO UPDATE SET value = EXCLUDED.value
            """);
        cmd.Parameters.AddWithValue("val", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("sqli-secret", ct);
    }

    // A saved card whose provider token is the flag — surfaces on a SQLi dump of saved_cards or an
    // admin view of a customer's payment details.
    private async Task PlacePciCard(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("pci-card", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO saved_cards (id, user_id, cardholder_name, payment_token, last4, expiry_month, expiry_year, created_at)
            VALUES (90, 3, 'C CHEN', @token, '4242', 12, 2028, '2026-08-20 10:00+00')
            ON CONFLICT (id) DO UPDATE SET payment_token = EXCLUDED.payment_token
            """);
        cmd.Parameters.AddWithValue("token", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("pci-card", ct);
    }

    // An order owned by a victim, whose notes carry the flag. Captured by becoming that victim —
    // a password-reset takeover or credential stuffing — then reading their order.
    private async Task PlaceVictimOrder(Dictionary<string, Guid> g, string slug, int orderId, int userId, CancellationToken ct)
    {
        if (!g.TryGetValue(slug, out var guid)) return;
        await using (var o = storeDb.CreateCommand("""
            INSERT INTO orders (id, user_id, status, notes, shipping_address, created_at, updated_at, shipped_at)
            VALUES (@oid, @uid, 'delivered', @notes, '12 Drake Avenue, Duckton, DT3 3CC', '2026-09-10 10:00+00', '2026-09-14 12:00+00', '2026-09-12 09:00+00')
            ON CONFLICT (id) DO UPDATE SET notes = EXCLUDED.notes
            """))
        {
            o.Parameters.AddWithValue("oid", orderId);
            o.Parameters.AddWithValue("uid", userId);
            o.Parameters.AddWithValue("notes", $"Account note. {Flag(guid)}");
            await o.ExecuteNonQueryAsync(ct);
        }
        await using (var i = storeDb.CreateCommand(
            "INSERT INTO order_items (id, order_id, product_id, quantity, unit_price) VALUES (@iid, @oid, 1, 1, 4.99) ON CONFLICT (id) DO NOTHING"))
        {
            i.Parameters.AddWithValue("iid", orderId + 8000);
            i.Parameters.AddWithValue("oid", orderId);
            await i.ExecuteNonQueryAsync(ct);
        }
        await MarkPlaced(slug, ct);
    }

    // A product that isn't shown in the catalogue list (visible = false). Reachable only by walking
    // product ids (GET /api/products/{id}); the flag is in its description.
    private async Task PlaceHiddenDuck(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("hidden-duck", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO products (id, sku, name, description, price, stock, image_url, visible)
            VALUES (99, 'DUCK-PROTO', 'Prototype Duck', @desc, 0.00, 0, '/images/ducks/classic.png', false)
            ON CONFLICT (id) DO UPDATE SET description = EXCLUDED.description, visible = false
            """);
        cmd.Parameters.AddWithValue("desc", $"Unreleased prototype — not for sale. {Flag(guid)}");
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("hidden-duck", ct);
    }

    // A secrets row the backup service reads and writes into the backups volume (backup-file flag).
    private async Task PlaceBackupSecret(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("backup-file", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO secrets (id, name, value) VALUES (2, 'backup-file', @val)
            ON CONFLICT (id) DO UPDATE SET value = EXCLUDED.value
            """);
        cmd.Parameters.AddWithValue("val", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("backup-file", ct);
    }

    // One Grafana annotation carrying the flag. An anonymous-admin attacker (VULN-GRAFANA-01) can read
    // annotations. Posted once (guarded by `placed`) so restarts don't pile up duplicates.
    private async Task PlaceGrafanaAnnotation(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("grafana-admin", out var guid)) return;
        if (await IsPlaced("grafana-admin", ct)) return;
        try
        {
            var http = httpFactory.CreateClient("grafana");
            using var req = new HttpRequestMessage(HttpMethod.Post, "/api/annotations")
            {
                Content = JsonContent.Create(new { text = $"Internal maintenance note — build token {Flag(guid)}", tags = new[] { "ctf-flag", "internal" } }),
            };
            req.Headers.Authorization = new AuthenticationHeaderValue(
                "Basic", Convert.ToBase64String(Encoding.ASCII.GetBytes("admin:admin")));
            using var resp = await http.SendAsync(req, ct);
            if (resp.IsSuccessStatusCode) await MarkPlaced("grafana-admin", ct);
            else log.LogWarning("Grafana annotation seeding returned {Status}", resp.StatusCode);
        }
        catch (Exception ex)
        {
            log.LogWarning(ex, "Grafana annotation seeding failed.");
        }
    }

    private async Task<bool> IsPlaced(string slug, CancellationToken ct)
    {
        await using var cmd = controlDb.CreateCommand("SELECT placed FROM ctf_flags WHERE slug = @s");
        cmd.Parameters.AddWithValue("s", slug);
        return await cmd.ExecuteScalarAsync(ct) is true;
    }

    private async Task MarkPlaced(string slug, CancellationToken ct)
    {
        await using var cmd = controlDb.CreateCommand("UPDATE ctf_flags SET placed = true WHERE slug = @s");
        cmd.Parameters.AddWithValue("s", slug);
        await cmd.ExecuteNonQueryAsync(ct);
    }
}
