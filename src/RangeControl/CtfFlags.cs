using Npgsql;

namespace RangeControl;

public sealed record CtfFlag(string Slug, Guid? Guid, string? VulnId, string Title, string WhereHint, int Points, bool Placed);
public sealed record FlagSubmission(long Id, string FlagText, string? Note, string? How, string? SourceIp, bool Recognised, string? MatchedSlug, DateTimeOffset At);

/// <summary>
/// Reads the CTF flag manifest (range_control.ctf_flags) and the attacker submissions
/// (duckstore.flag_submissions) for the Range Control scoreboard, and matches submitted text to the
/// per-deployment flag guids. Flag values are never in Git — they are generated by <see cref="FlagSeeder"/>.
/// </summary>
public sealed class CtfFlagService(NpgsqlDataSource controlDb, NpgsqlDataSource storeDb)
{
    public async Task<IReadOnlyList<CtfFlag>> GetManifestAsync(CancellationToken ct = default)
    {
        var list = new List<CtfFlag>();
        await using var cmd = controlDb.CreateCommand(
            "SELECT slug, guid, vuln_id, title, where_hint, points, placed FROM ctf_flags ORDER BY points, slug");
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
            list.Add(new CtfFlag(r.GetString(0), r.IsDBNull(1) ? null : r.GetGuid(1),
                r.IsDBNull(2) ? null : r.GetString(2), r.GetString(3), r.GetString(4), r.GetInt32(5), r.GetBoolean(6)));
        return list;
    }

    public async Task<IReadOnlyList<FlagSubmission>> GetSubmissionsAsync(CancellationToken ct = default)
    {
        var list = new List<FlagSubmission>();
        await using var cmd = storeDb.CreateCommand(
            "SELECT id, flag_text, note, how, source_ip, recognised, matched_slug, submitted_at FROM flag_submissions ORDER BY submitted_at DESC LIMIT 500");
        await using var r = await cmd.ExecuteReaderAsync(ct);
        while (await r.ReadAsync(ct))
            list.Add(new FlagSubmission(r.GetInt64(0), r.GetString(1), r.IsDBNull(2) ? null : r.GetString(2),
                r.IsDBNull(3) ? null : r.GetString(3), r.IsDBNull(4) ? null : r.GetString(4), r.GetBoolean(5),
                r.IsDBNull(6) ? null : r.GetString(6), r.GetFieldValue<DateTimeOffset>(7)));
        return list;
    }
}

/// <summary>
/// Generates the per-deployment flag guids (so real flag values never live in Git) and places the
/// data-embedded flags into the store data. Runs once at startup; idempotent.
/// </summary>
public sealed class FlagSeeder(NpgsqlDataSource controlDb, NpgsqlDataSource storeDb, ILogger<FlagSeeder> log) : IHostedService
{
    private static string Flag(Guid g) => $"flag{{{g}}}";

    public async Task StartAsync(CancellationToken ct)
    {
        try
        {
            // 1. One GUID per flag that doesn't have one yet (per deployment).
            await using (var gen = controlDb.CreateCommand("UPDATE ctf_flags SET guid = gen_random_uuid() WHERE guid IS NULL"))
                await gen.ExecuteNonQueryAsync(ct);

            // 2. Read the guids we place as data.
            var g = new Dictionary<string, Guid>();
            await using (var read = controlDb.CreateCommand("SELECT slug, guid FROM ctf_flags WHERE guid IS NOT NULL"))
            await using (var r = await read.ExecuteReaderAsync(ct))
                while (await r.ReadAsync(ct)) g[r.GetString(0)] = r.GetGuid(1);

            // 3. Place the data-embedded flags in duckstore (idempotent upserts).
            await PlaceNoLoginUser(g, ct);
            await PlaceIdorOrder(g, ct);
            await PlaceSqliSecret(g, ct);

            log.LogInformation("CTF flags generated; data flags placed (nologin-user, idor-order, sqli-secret).");
        }
        catch (Exception ex)
        {
            log.LogWarning(ex, "CTF flag seeding failed.");
        }
    }

    public Task StopAsync(CancellationToken ct) => Task.CompletedTask;

    // A user that exists but can never sign in (NULL password). The flag is its display_name, so it
    // surfaces on any user enumeration or a dump of the users table.
    private async Task PlaceNoLoginUser(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("nologin-user", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO users (id, email, display_name, role, created_at)
            VALUES (98, 'service.account@duckstore.test', @name, 'customer', '2026-07-15 00:00+00')
            ON CONFLICT (id) DO UPDATE SET display_name = EXCLUDED.display_name
            """);
        cmd.Parameters.AddWithValue("name", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("nologin-user", ct);
    }

    // An order owned by Bob (user 2). Reading it as anyone else is IDOR; the flag is in the notes.
    private async Task PlaceIdorOrder(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("idor-order", out var guid)) return;
        await using (var o = storeDb.CreateCommand("""
            INSERT INTO orders (id, user_id, status, notes, shipping_address, created_at, updated_at, shipped_at)
            VALUES (1098, 2, 'delivered', @notes, '7 Mallard Street, Duckton, DT2 2BB', '2026-09-20 10:00+00', '2026-09-25 12:00+00', '2026-09-22 09:00+00')
            ON CONFLICT (id) DO UPDATE SET notes = EXCLUDED.notes
            """))
        {
            o.Parameters.AddWithValue("notes", $"Leave with neighbour. {Flag(guid)}");
            await o.ExecuteNonQueryAsync(ct);
        }
        await using (var i = storeDb.CreateCommand(
            "INSERT INTO order_items (id, order_id, product_id, quantity, unit_price) VALUES (9098, 1098, 1, 1, 4.99) ON CONFLICT (id) DO NOTHING"))
            await i.ExecuteNonQueryAsync(ct);
        await MarkPlaced("idor-order", ct);
    }

    // A row in the secrets table, reachable only by SQL injection in the product search (UNION dump).
    private async Task PlaceSqliSecret(Dictionary<string, Guid> g, CancellationToken ct)
    {
        if (!g.TryGetValue("sqli-secret", out var guid)) return;
        await using var cmd = storeDb.CreateCommand("""
            INSERT INTO secrets (id, name, value) VALUES (1, 'ctf-flag', @val)
            ON CONFLICT (id) DO UPDATE SET value = EXCLUDED.value
            """);
        cmd.Parameters.AddWithValue("val", Flag(guid));
        await cmd.ExecuteNonQueryAsync(ct);
        await MarkPlaced("sqli-secret", ct);
    }

    private async Task MarkPlaced(string slug, CancellationToken ct)
    {
        await using var cmd = controlDb.CreateCommand("UPDATE ctf_flags SET placed = true WHERE slug = @s");
        cmd.Parameters.AddWithValue("s", slug);
        await cmd.ExecuteNonQueryAsync(ct);
    }
}
